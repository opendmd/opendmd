/// The code of an error message: of the entries whose fragments all occur
/// in `msg`, the one with the most fragment text in all (so a sentence with
/// a longer, more particular match beats a shorter, general one); a tie goes
/// to the lower code. `None` for a message no entry knows.
pub fn code_of(msg: &str) -> Option<u16> {
    let mut best: Option<(usize, u16)> = None;
    for d in ERRORS {
        if d.matches.iter().all(|m| msg.contains(m)) {
            let n: usize = d.matches.iter().map(|m| m.len()).sum();
            if best.is_none_or(|(b, _)| n > b) {
                best = Some((n, d.code));
            }
        }
    }
    best.map(|(_, c)| c)
}

/// The entry for `code`.
pub fn doc(code: u16) -> Option<&'static ErrorDoc> {
    ERRORS.binary_search_by_key(&code, |d| d.code).ok().map(|i| &ERRORS[i])
}

/// "E203".
pub fn label(code: u16) -> String {
    format!("E{code:03}")
}

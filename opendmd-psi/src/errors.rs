//! The error index: a code for every sentence the compiler can say, found
//! from the sentence. The firmware carries none of this (`Error` has no
//! code field): tools (`psi check`, the language service, the gallery
//! checker) and the language reference's error index read it, so it is
//! built only with the `docs` feature. `tests/diagnostics.rs` pins every
//! entry to a source that produces it and checks that every sentence in
//! `compile.rs` has a code.
//!
//! Not part of the crate's API (`#[doc(hidden)]`).

use alloc::format;

//! The updater's picture (`ota/updater`, `docs/ota.md`): [`boot::installing`]
//! with no dot lit, packed at build time into a C header, so the updater
//! (a small C app with no font code) can put it on the panel while it
//! copies a firmware image into flash, and light [`boot::INSTALL_DOTS`] one
//! at a time over it.
//!
//! The packing: at most four colours, black first; two bits a pixel,
//! row-major, pixel `i = y * WIDTH + x` in byte `i / 4` at bit `(i % 4) * 2`
//! (1 KB for 128x32). The header is committed
//! (`ota/updater/main/picture.h`); `make updater-picture` writes it again
//! (`cargo run --example updater_picture`) and a test here fails when the
//! committed copy is not what this module makes.

use crate::boot::{self, INSTALL_DOT, INSTALL_DOTS, INSTALL_DOT_COLOUR};
use crate::canvas::{Canvas, Rgb, HEIGHT, WIDTH};
use std::fmt::Write;

/// Colours a packed picture can hold (two bits a pixel).
pub const COLOURS: usize = 4;

/// A picture packed for the updater.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Packed {
    /// Index 0 is black; unused entries are black too.
    pub palette: [Rgb; COLOURS],
    /// `WIDTH * HEIGHT / 4` bytes, two bits a pixel.
    pub bits: Vec<u8>,
}

/// `canvas` packed, or `None` if it has more than [`COLOURS`] colours
/// (black counted).
pub fn pack(canvas: &Canvas) -> Option<Packed> {
    let mut palette = vec![Rgb::BLACK];
    let mut bits = vec![0u8; WIDTH * HEIGHT / 4];
    for (i, &p) in canvas.as_slice().iter().enumerate() {
        let k = match palette.iter().position(|&c| c == p) {
            Some(k) => k,
            None if palette.len() < COLOURS => {
                palette.push(p);
                palette.len() - 1
            }
            None => return None,
        };
        bits[i / 4] |= (k as u8) << ((i % 4) * 2);
    }
    palette.resize(COLOURS, Rgb::BLACK);
    Some(Packed {
        palette: palette.try_into().ok()?,
        bits,
    })
}

/// [`pack`]'s inverse.
pub fn unpack(p: &Packed) -> Canvas {
    let mut c = Canvas::new();
    for y in 0..HEIGHT {
        for x in 0..WIDTH {
            let i = y * WIDTH + x;
            let k = (p.bits[i / 4] >> ((i % 4) * 2)) & 3;
            c.set(x, y, p.palette[usize::from(k)]);
        }
    }
    c
}

/// The updater's base picture: [`boot::installing`] with no dot lit.
pub fn base() -> Canvas {
    let mut c = Canvas::new();
    boot::installing(&mut c, [false; INSTALL_DOTS.len()]);
    c
}

/// `ota/updater/main/picture.h`: the base picture packed, and the dots.
pub fn c_header() -> String {
    let p = pack(&base()).expect("the installing picture has at most four colours");
    let mut s = String::new();
    s.push_str(
        "/*\n * The updater's picture: generated by `make updater-picture`\n \
         * (opendmd-core/src/updater_picture.rs, from boot::installing with no\n \
         * dot lit). Do not edit: `make test` fails when this is stale.\n *\n \
         * Two bits a pixel, row-major: pixel i = y * PICTURE_W + x is in byte\n \
         * i / 4 at bit (i % 4) * 2, an index into PICTURE_PALETTE (0 = black).\n \
         * The dots are PICTURE_DOT x PICTURE_DOT blocks at PICTURE_DOT_XY\n \
         * (top-left), lit one at a time in PICTURE_DOT_RGB over black.\n */\n",
    );
    s.push_str("#ifndef OPENDMD_UPDATER_PICTURE_H\n#define OPENDMD_UPDATER_PICTURE_H\n\n");
    s.push_str("#include <stdint.h>\n\n");
    let _ = writeln!(s, "#define PICTURE_W {WIDTH}");
    let _ = writeln!(s, "#define PICTURE_H {HEIGHT}");
    let _ = writeln!(s, "#define PICTURE_COLOURS {COLOURS}");
    let _ = writeln!(s, "#define PICTURE_DOTS {}", INSTALL_DOTS.len());
    let _ = writeln!(s, "#define PICTURE_DOT {INSTALL_DOT}\n");
    s.push_str("static const uint8_t PICTURE_PALETTE[PICTURE_COLOURS][3] = {\n");
    for c in p.palette {
        let _ = writeln!(s, "    {{{}, {}, {}}},", c.r, c.g, c.b);
    }
    s.push_str("};\n\n");
    s.push_str("static const uint8_t PICTURE_BITS[PICTURE_W * PICTURE_H / 4] = {\n");
    for row in p.bits.chunks(16) {
        s.push_str("   ");
        for b in row {
            let _ = write!(s, " 0x{b:02x},");
        }
        s.push('\n');
    }
    s.push_str("};\n\n");
    s.push_str("static const uint8_t PICTURE_DOT_XY[PICTURE_DOTS][2] = {");
    for (i, (x, y)) in INSTALL_DOTS.iter().enumerate() {
        let _ = write!(s, "{}{{{x}, {y}}}", if i == 0 { "" } else { ", " });
    }
    s.push_str("};\n");
    let c = INSTALL_DOT_COLOUR;
    let _ = writeln!(
        s,
        "static const uint8_t PICTURE_DOT_RGB[3] = {{{}, {}, {}}};\n",
        c.r, c.g, c.b
    );
    s.push_str("#endif\n");
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    const COMMITTED: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../ota/updater/main/picture.h");

    #[test]
    fn packing_round_trips() {
        let b = base();
        let p = pack(&b).unwrap();
        assert_eq!(p.palette[0], Rgb::BLACK);
        assert_eq!(p.bits.len(), 1024);
        assert_eq!(unpack(&p).as_slice(), b.as_slice());
        // Each colour of the picture is in the palette once.
        let used: Vec<Rgb> = p.palette.iter().copied().filter(|c| *c != Rgb::BLACK).collect();
        for (i, c) in used.iter().enumerate() {
            assert!(!used[i + 1..].contains(c), "{c:?} twice");
        }
        // A fifth colour does not pack.
        let mut five = Canvas::new();
        for (i, v) in [10u8, 20, 30, 40].into_iter().enumerate() {
            five.set(i, 0, Rgb::new(v, 0, 0));
        }
        assert!(pack(&five).is_none());
        five.set(3, 0, Rgb::new(10, 0, 0));
        assert_eq!(unpack(&pack(&five).unwrap()).as_slice(), five.as_slice());
    }

    #[test]
    fn the_base_and_its_dots_are_the_firmware_screen() {
        let b = base();
        // The title and "Don't unplug" are there; the middle line is empty
        // but for the dots.
        assert!(b.as_slice().iter().filter(|p| **p != Rgb::BLACK).count() > 100);
        for y in 18..24 {
            for x in 0..WIDTH {
                assert_eq!(b.get(x, y), Rgb::BLACK, "middle line at {x},{y}");
            }
        }
        // The base with every dot lit is the firmware's own screen.
        let mut all = b.clone();
        for &(x0, y0) in &INSTALL_DOTS {
            for y in y0..y0 + INSTALL_DOT {
                for x in x0..x0 + INSTALL_DOT {
                    all.set(x, y, INSTALL_DOT_COLOUR);
                }
            }
        }
        let mut fw = Canvas::new();
        boot::update_notice(&mut fw, boot::UpdateStage::Installing, "1.0.0-beta.17");
        assert_eq!(all.as_slice(), fw.as_slice());
        // The dots do not touch each other and fit the panel.
        for w in INSTALL_DOTS.windows(2) {
            assert!(w[1].0 > w[0].0 + INSTALL_DOT);
        }
        for &(x, y) in &INSTALL_DOTS {
            assert!(x + INSTALL_DOT <= WIDTH && y + INSTALL_DOT <= HEIGHT);
        }
        // Centred, give or take a pixel.
        let left = INSTALL_DOTS[0].0;
        let right = WIDTH - (INSTALL_DOTS[2].0 + INSTALL_DOT);
        assert!(left.abs_diff(right) <= 1, "{left} vs {right}");
    }

    #[test]
    fn the_committed_header_is_current() {
        let want = c_header();
        let have = std::fs::read_to_string(COMMITTED).unwrap_or_default();
        assert!(
            have == want,
            "ota/updater/main/picture.h is stale: run `make updater-picture` and commit it"
        );
        // It holds the whole bitmap.
        assert_eq!(want.matches("0x").count(), WIDTH * HEIGHT / 4);
    }
}

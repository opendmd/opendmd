//! Bitmap text for the panel: two public-domain fonts, drawing, and the
//! title-card layout.
//!
//! # Fonts and their licence
//!
//! Both are the X11 "misc-fixed" bitmap fonts, whose BDF sources say
//! `COPYRIGHT "Public domain font.  Share and enjoy."` (xorg `font/misc-misc`,
//! `5x7.bdf` rev 1.38 by Markus Kuhn's ucs-fonts, and `4x6.bdf`). The tables
//! below are generated from those BDF files, printable ASCII (32..=126) only:
//!
//! - [`Font::Normal`] — `5x7`: 5-pixel advance, 7 rows (6 above the
//!   baseline, 1 descender). 25 characters fit across the panel.
//! - [`Font::Small`] — `4x6`: 4-pixel advance, 6 rows (5 + 1). 32 fit.
//!
//! Each glyph is one byte per row, most significant bit leftmost. Anything
//! outside ASCII is folded first ([`fold_char`]: `é` -> `e`, `–` -> `-`,
//! otherwise `?`), so a game called "Pokémon" still reads.
//!
//! # Layout
//!
//! [`draw_text`] draws at a pixel position; [`text_width`], [`fit`]
//! (ellipsise to a width — v1 never scrolls) and [`draw_centered`] build on
//! it, and [`title_card`] is the one layout the firmware uses: a game title
//! (up to two lines of the normal font, or one line at double size when it is
//! short and alone) over a smaller second line (the console's name).

use crate::canvas::{Canvas, Rgb, HEIGHT, WIDTH};

/// Title text on a card: an amber-ish white.
pub const TITLE_COLOUR: Rgb = Rgb::new(255, 214, 150);
/// A card's second line: a deeper amber.
pub const SUBTITLE_COLOUR: Rgb = Rgb::new(210, 120, 30);

/// The two fonts.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Font {
    /// misc-fixed 5x7.
    Normal,
    /// misc-fixed 4x6.
    Small,
}

impl Font {
    /// Horizontal distance from one character to the next, at scale 1 (the
    /// glyph plus its one-pixel gap).
    pub const fn advance(self) -> usize {
        match self {
            Font::Normal => 5,
            Font::Small => 4,
        }
    }

    /// Rows per character cell, descender included, at scale 1.
    pub const fn height(self) -> usize {
        match self {
            Font::Normal => 7,
            Font::Small => 6,
        }
    }

    fn rows(self, c: char) -> &'static [u8] {
        let i = (c as usize).wrapping_sub(32);
        match self {
            Font::Normal => &FONT_5X7[if i < 95 { i } else { b'?' as usize - 32 }],
            Font::Small => &FONT_4X6[if i < 95 { i } else { b'?' as usize - 32 }],
        }
    }
}

/// `c` as a character the fonts have: printable ASCII as it is, common
/// accented Latin letters without their accent, typographic dashes and
/// quotes as their ASCII cousins, whitespace as a space, anything else `?`.
pub fn fold_char(c: char) -> char {
    match c {
        ' '..='~' => c,
        'À'..='Å' => 'A',
        'à'..='å' => 'a',
        'Ç' => 'C',
        'ç' => 'c',
        'È'..='Ë' => 'E',
        'è'..='ë' => 'e',
        'Ì'..='Ï' => 'I',
        'ì'..='ï' => 'i',
        'Ñ' => 'N',
        'ñ' => 'n',
        'Ò'..='Ö' | 'Ø' => 'O',
        'ò'..='ö' | 'ø' => 'o',
        'Ù'..='Ü' => 'U',
        'ù'..='ü' => 'u',
        'Ý' => 'Y',
        'ý' | 'ÿ' => 'y',
        'ß' => 's',
        '‐'..='―' => '-',
        '‘' | '’' | '′' => '\'',
        '“' | '”' | '″' => '"',
        '…' => '.',
        c if c.is_whitespace() => ' ',
        _ => '?',
    }
}

/// Width in pixels of `text` in `font` at `scale`, without the gap after
/// the last character (so it centres honestly). 0 for an empty string.
pub fn text_width(font: Font, text: &str, scale: usize) -> usize {
    let n = text.chars().count();
    if n == 0 {
        0
    } else {
        (n * font.advance() - 1) * scale
    }
}

/// Draw `text` in the normal font at scale 1 with its top-left corner at
/// `(x, y)`. Pixels off the panel are dropped; only lit pixels are written
/// (and marked), so text can go over a picture. Returns the width drawn.
pub fn draw_text(canvas: &mut Canvas, x: i32, y: i32, text: &str, colour: Rgb) -> usize {
    draw_text_with(canvas, x, y, text, colour, Font::Normal, 1)
}

/// [`draw_text`] in either font, each font pixel drawn as a `scale` x
/// `scale` block.
pub fn draw_text_with(
    canvas: &mut Canvas,
    x: i32,
    y: i32,
    text: &str,
    colour: Rgb,
    font: Font,
    scale: usize,
) -> usize {
    let scale = scale.max(1);
    let mut cx = x;
    for c in text.chars() {
        let rows = font.rows(fold_char(c));
        for (ry, bits) in rows.iter().enumerate() {
            for rx in 0..font.advance() {
                if bits & (0x80 >> rx) == 0 {
                    continue;
                }
                for dy in 0..scale {
                    for dx in 0..scale {
                        let px = cx + (rx * scale + dx) as i32;
                        let py = y + (ry * scale + dy) as i32;
                        if (0..WIDTH as i32).contains(&px) && (0..HEIGHT as i32).contains(&py) {
                            canvas.set(px as usize, py as usize, colour);
                        }
                    }
                }
            }
        }
        cx += (font.advance() * scale) as i32;
    }
    text_width(font, text, scale)
}

/// `text` if it fits in `max` pixels, else as much of it as fits followed
/// by `...` (trailing spaces dropped before the dots).
pub fn fit(font: Font, text: &str, max: usize, scale: usize) -> String {
    let text = text.trim();
    if text_width(font, text, scale) <= max {
        return text.to_string();
    }
    let per = font.advance() * scale;
    // Characters that fit with the three dots after them.
    let room = (max + scale).saturating_sub(3 * per) / per;
    let kept: String = text.chars().take(room).collect();
    format!("{}...", kept.trim_end())
}

/// Break `text` into at most two lines of at most `max` pixels, at spaces
/// where it can; the second line is ellipsised if it still does not fit.
/// One line if it fits as it is.
pub fn wrap2(font: Font, text: &str, max: usize, scale: usize) -> (String, Option<String>) {
    let text = text.trim();
    if text_width(font, text, scale) <= max {
        return (text.to_string(), None);
    }
    let per = font.advance() * scale;
    let cap = (max + scale) / per;
    // The last space at or before the break, else a hard break.
    let chars: Vec<char> = text.chars().collect();
    let cut = chars[..cap.min(chars.len())]
        .iter()
        .rposition(|c| *c == ' ')
        .filter(|&i| i > 0)
        .unwrap_or(cap);
    let first: String = chars[..cut].iter().collect();
    let rest: String = chars[cut..].iter().collect();
    (
        first.trim_end().to_string(),
        Some(fit(font, rest.trim_start(), max, scale)),
    )
}

/// Draw `text` centred across the panel with its top at `y`.
pub fn draw_centered(
    canvas: &mut Canvas,
    y: i32,
    text: &str,
    colour: Rgb,
    font: Font,
    scale: usize,
) {
    let w = text_width(font, text, scale) as i32;
    draw_text_with(canvas, (WIDTH as i32 - w) / 2, y, text, colour, font, scale);
}

/// A title card on a black panel: `title` in the normal font — at double
/// size if there is no `subtitle` and it fits, else on one or two lines —
/// and `subtitle` (may be empty) below in the small font, everything
/// centred and ellipsised to the panel width. The canvas is cleared first.
pub fn title_card(canvas: &mut Canvas, title: &str, subtitle: &str) {
    canvas.clear();
    let title = title.trim();
    let subtitle = subtitle.trim();
    let big = Font::Normal;
    if subtitle.is_empty() && text_width(big, title, 2) <= WIDTH - 4 {
        let h = (big.height() * 2) as i32;
        draw_centered(
            canvas,
            (HEIGHT as i32 - h) / 2 + 1,
            title,
            TITLE_COLOUR,
            big,
            2,
        );
        return;
    }
    let (first, second) = wrap2(big, title, WIDTH - 2, 1);
    let sub = fit(Font::Small, subtitle, WIDTH - 2, 1);
    // Rows: one title line 7..14, the subtitle 20..26; two title lines 2..9
    // and 11..18, the subtitle 23..29. Without a subtitle the title block
    // is centred.
    let (y1, y2, ys) = match (&second, sub.is_empty()) {
        (None, false) => (7, 0, 20),
        (Some(_), false) => (2, 11, 23),
        (None, true) => (12, 0, 0),
        (Some(_), true) => (8, 17, 0),
    };
    draw_centered(canvas, y1, &first, TITLE_COLOUR, big, 1);
    if let Some(second) = &second {
        draw_centered(canvas, y2, second, TITLE_COLOUR, big, 1);
    }
    if !sub.is_empty() {
        draw_centered(canvas, ys, &sub, SUBTITLE_COLOUR, Font::Small, 1);
    }
}


#[cfg(test)]
mod tests {
    use super::*;

    fn lit(c: &Canvas) -> Vec<(usize, usize)> {
        let mut v = Vec::new();
        for y in 0..HEIGHT {
            for x in 0..WIDTH {
                if c.get(x, y) != Rgb::BLACK {
                    v.push((x, y));
                }
            }
        }
        v
    }

    #[test]
    fn glyphs_are_the_bdf_ones() {
        // 'A' in 5x7: .##. / #..# / #..# / #### / #..# / #..# / ....
        assert_eq!(
            Font::Normal.rows('A'),
            &[0x60, 0x90, 0x90, 0xf0, 0x90, 0x90, 0x00]
        );
        // 'g' in 4x6 has a descender in the last row.
        assert_eq!(Font::Small.rows('g')[5], 0xc0);
        assert!(Font::Normal.rows(' ').iter().all(|r| *r == 0));
        // Every glyph fits its advance (the last column is the gap).
        for c in ' '..='~' {
            assert!(Font::Normal.rows(c).iter().all(|r| r & 0x07 == 0), "{c:?}");
            assert!(Font::Small.rows(c).iter().all(|r| r & 0x0f == 0), "{c:?}");
        }
    }

    #[test]
    fn draws_exactly_the_glyph() {
        let mut c = Canvas::new();
        c.dirty_mut().clear();
        let w = draw_text(&mut c, 10, 3, "A", TITLE_COLOUR);
        assert_eq!(w, 4);
        let px = lit(&c);
        assert_eq!(px.len(), 14);
        assert!(px.contains(&(11, 3)) && px.contains(&(10, 4)) && px.contains(&(13, 6)));
        assert_eq!(c.dirty().count(), 14, "marks what it lights");
        // Scaled: every pixel a 2x2 block.
        let mut c = Canvas::new();
        draw_text_with(&mut c, 0, 0, "A", TITLE_COLOUR, Font::Normal, 2);
        assert_eq!(lit(&c).len(), 56);
    }

    #[test]
    fn clips_at_the_edges() {
        let mut c = Canvas::new();
        draw_text(&mut c, -2, -3, "WW", TITLE_COLOUR);
        draw_text(&mut c, 125, 29, "WW", TITLE_COLOUR);
        assert!(!lit(&c).is_empty());
    }

    #[test]
    fn folds_accents_and_unknowns() {
        assert_eq!(fold_char('é'), 'e');
        assert_eq!(fold_char('Ö'), 'O');
        assert_eq!(fold_char('–'), '-');
        assert_eq!(fold_char('’'), '\'');
        assert_eq!(fold_char('漢'), '?');
        let (mut a, mut b) = (Canvas::new(), Canvas::new());
        draw_text(&mut a, 0, 0, "Pokémon", TITLE_COLOUR);
        draw_text(&mut b, 0, 0, "Pokemon", TITLE_COLOUR);
        assert_eq!(a, b);
    }

    #[test]
    fn widths_fit_and_wrap() {
        assert_eq!(text_width(Font::Normal, "", 1), 0);
        assert_eq!(text_width(Font::Normal, "Sonic the Hedgehog 3", 1), 99);
        assert_eq!(text_width(Font::Small, "Mega Drive", 1), 39);
        assert_eq!(fit(Font::Normal, "Short", 128, 1), "Short");
        let long = "The Legend of Zelda - A Link to the Past and Four Swords";
        let f = fit(Font::Normal, long, 128, 1);
        assert!(
            f.ends_with("...") && text_width(Font::Normal, &f, 1) <= 128,
            "{f}"
        );
        let (a, b) = wrap2(Font::Normal, long, 126, 1);
        assert_eq!(a, "The Legend of Zelda - A");
        let b = b.unwrap();
        assert!(
            b.starts_with("Link to the Past") && b.ends_with("..."),
            "{b}"
        );
        assert!(text_width(Font::Normal, &b, 1) <= 126);
        assert_eq!(wrap2(Font::Normal, "Sonic", 126, 1), ("Sonic".into(), None));
        // No space to break at: a hard break.
        let (a, b) = wrap2(Font::Normal, &"X".repeat(40), 126, 1);
        assert_eq!(a.len(), 25);
        assert_eq!(b.as_deref(), Some("XXXXXXXXXXXXXXX"));
    }

    #[test]
    fn title_card_layout() {
        let mut c = Canvas::new();
        title_card(&mut c, "Sonic the Hedgehog 3", "Mega Drive");
        let px = lit(&c);
        let rows = |lo: usize, hi: usize| px.iter().filter(|(_, y)| (lo..hi).contains(y)).count();
        assert!(rows(7, 14) > 0 && rows(20, 26) > 0);
        assert_eq!(rows(0, 7) + rows(15, 20) + rows(27, 32), 0);
        // Centred: the lit span's margins differ by at most a pixel or two.
        let (l, r) = (
            px.iter().map(|p| p.0).min().unwrap(),
            px.iter().map(|p| p.0).max().unwrap(),
        );
        assert!((l as i32 - (WIDTH - 1 - r) as i32).abs() <= 2, "{l} {r}");
        assert!(px
            .iter()
            .filter(|(_, y)| *y < 15)
            .all(|&(x, y)| c.get(x, y) == TITLE_COLOUR));
        assert!(px
            .iter()
            .filter(|(_, y)| *y >= 20)
            .all(|&(x, y)| c.get(x, y) == SUBTITLE_COLOUR));

        // Alone and short: double size.
        title_card(&mut c, "Mega Drive", "");
        let px = lit(&c);
        let (t, b) = (
            px.iter().map(|p| p.1).min().unwrap(),
            px.iter().map(|p| p.1).max().unwrap(),
        );
        assert!(b - t >= 10, "double height, {t}..{b}");

        // Long: two title lines, then the subtitle; nothing past the edge.
        title_card(
            &mut c,
            "Street Fighter II' - Special Champion Edition",
            "Mega Drive",
        );
        let px = lit(&c);
        assert!(px.iter().any(|p| p.1 < 9) && px.iter().any(|p| (11..18).contains(&p.1)));
        assert!(px.iter().any(|p| p.1 >= 23));

        // The card clears what was there.
        c.fill(Rgb::new(9, 9, 9));
        title_card(&mut c, "A", "");
        assert!(c
            .as_slice()
            .iter()
            .all(|p| *p == Rgb::BLACK || *p == TITLE_COLOUR));
    }
}
